import assert from 'node:assert/strict';
import { build } from 'esbuild';
const source = `
import {buildGraph} from './src/lets-excalidraw/app/tools/graph-model';
import {layout,detectDirection} from './src/lets-excalidraw/app/tools/graph-layout';
import {exportMermaid} from './src/lets-excalidraw/app/tools/mermaid-export';
export {buildGraph,layout,detectDirection,exportMermaid};
`;
const result = await build({stdin:{contents:source, resolveDir:process.cwd(), sourcefile:'migrated-graph-fixture.ts'},bundle:true,write:false,format:'esm',platform:'node'});
const {buildGraph,layout,detectDirection,exportMermaid} = await import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64'));
const shape = (id,x,y,width=120,height=40,extra={}) => ({id,type:'rectangle',x,y,width,height,isDeleted:false,...extra});
const arrow = (id,from,to,extra={}) => ({id,type:'arrow',isDeleted:false,startBinding:{elementId:from},endBinding:{elementId:to},endArrowhead:'arrow',...extra});
const elements = [shape('a',0,0),shape('b',-200,100),shape('c',200,100),shape('d',0,300),arrow('ab','a','b'),arrow('ac','a','c'),arrow('bd','b','d'),arrow('cd','c','d')];
const graph=buildGraph(elements);
assert.equal(graph.nodes.length,4);
assert.equal(graph.edges.length,4);
assert.equal(detectDirection(graph),'TD');
const positions=layout(graph);
assert.equal(positions.size,4);
assert.ok(positions.get('a').y < positions.get('b').y && positions.get('b').y < positions.get('d').y);
assert.equal(positions.get('b').y,positions.get('c').y);
assert.ok(exportMermaid(graph,elements).startsWith('flowchart TD'));
const chain=buildGraph([shape('l',0,0),shape('r',300,0),arrow('lr','l','r',{strokeStyle:'dashed'})]);
assert.equal(detectDirection(chain),'LR');
assert.ok(layout(chain).get('l').x < layout(chain).get('r').x);
assert.ok(exportMermaid(chain,[]).includes('-.->'));
const mind=buildGraph([shape('m1',0,0,120,40,{customData:{dodoMind:{mapId:'map'}}}),shape('m2',0,150,120,40,{customData:{dodoMind:{mapId:'map',parentId:'m1'}}}),arrow('edge','m1','m2',{endArrowhead:null})]);
assert.ok(exportMermaid(mind,[]).includes('n1 --> n2'));
const labelled=buildGraph([shape('a',0,0),shape('b',0,150),arrow('edge','a','b'),{id:'label',type:'text',containerId:'edge',width:90,height:24,text:'success'}]);
assert.equal(labelled.edges[0].label.height,24);
assert.ok(exportMermaid(labelled,[...labelled.nodes.map(n=>n.element),labelled.edges[0].element,{id:'label',type:'text',containerId:'edge',text:'success'}]).includes('"success"'));
console.log('PASS: migrated graph model/layout, TD/LR direction, label spacing, mind edges, and Mermaid export');
